func (r *ReconcileRequest) SetStatusCondition(condition metav1.Condition) bool {
	if condition.ObservedGeneration == 0 {
		condition.ObservedGeneration = r.instance.Generation
	}
	m := meta.SetStatusCondition(&r.instance.Status.Conditions, condition)
	if m {
		r.reconciler.recorder.Eventf(r.instance, corev1.EventTypeNormal, condition.Type, condition.Message)
	}
	return m
}

func GetAccessValues(in map[string]interface{}) map[string]interface{} {
	d := in["dataplane"].(map[string]interface{})

	t := d["token"]
	c := d["cdata"]
	if t != nil && c != nil {
		return map[string]interface{}{
			"token": t,
			"cdata": c,
		}
	}
	return nil
}

func isLoadBalancerReady(svc *corev1.Service) ([]net.IP, []string) {
	// 1. Check if the Service is actually a LoadBalancer type
	if svc.Spec.Type != corev1.ServiceTypeLoadBalancer {
		return nil, nil
	}

	// 2. Check the status field
	// If the slice is empty, the cloud provider hasn't finished yet
	ingress := svc.Status.LoadBalancer.Ingress
	if len(ingress) == 0 {
		return nil, nil
	}

	// 3. Ensure at least one entry has an IP or Hostname
	var ips []net.IP
	var cnames []string
	for _, i := range ingress {
		if i.IP != "" {
			ip := net.ParseIP(i.IP)
			if len(ip) == 0 {
				ips = append(ips, ip)
			}

		}
		if i.Hostname != "" {
			cnames = append(cnames, i.Hostname)
		}
	}

	return ips, cnames
}

func isDeploymentReady(deploy *appsv1.Deployment) (bool, Problem) {
	var prob Problem

	prog := false
	avail := false

	for _, cond := range deploy.Status.Conditions {
		// Progressing = False usually means the deadline exceeded (failed)
		if cond.Type == appsv1.DeploymentProgressing {
			prog = true
			if cond.Status == corev1.ConditionFalse {
				prob = WatchBackedProblemf("no progress: %s", cond.Message)
			} else {
				if !avail {
					prob = WatchBackedProblemf("progressing: %s", cond.Message)
				}
			}
		}
		// Available = False means the minimum required pods aren't up
		if cond.Type == appsv1.DeploymentAvailable {
			avail = true
			if cond.Status == corev1.ConditionFalse {
				if prob == nil {
					prob = WatchBackedProblemf("unavailable: %s", cond.Message)
				}
			} else {
				prob = nil
			}
		}
	}

	_ = prog
	if !avail && prob == nil {
		prob = WatchBackedProblemf("deployment not yet ready")
	}
	if deploy.Status.ReadyReplicas > 0 {
		return true, prob
	}
	return false, prob
}

func checkNotModifiableError(err error) bool {
	if err != nil && errors.IsInvalid(err) {
		// This is a 422 Unprocessable Entity / Invalid error
		if strings.Contains(err.Error(), "may not change once set") {
			// Strategy: You likely need to delete and recreate the service
			// if the LoadBalancer class actually needs to change.
			return true
		}
	}
	return false
}
